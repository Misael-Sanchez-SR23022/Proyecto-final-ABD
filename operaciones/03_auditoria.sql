-- 2. IMPLEMENTACIÓN DE BITÁCORA DE AUDITORÍA MEDIANTE TRIGGERS
CREATE TABLE IF NOT EXISTS auditoria_log (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(60) NOT NULL DEFAULT current_user,
    fecha TIMESTAMP NOT NULL DEFAULT now(),
    tabla VARCHAR(60) NOT NULL,
    operacion VARCHAR(10) NOT NULL,
    datos JSONB
);

CREATE OR REPLACE FUNCTION fn_auditoria_general()
RETURNS TRIGGER AS $$
BEGIN
    IF (TG_OP = 'DELETE') THEN
        INSERT INTO auditoria_log (usuario, fecha, tabla, operacion, datos)
        VALUES (current_user, now(), TG_TABLE_NAME, TG_OP, to_jsonb(OLD));
        RETURN OLD;
    ELSIF (TG_OP = 'UPDATE') THEN
        INSERT INTO auditoria_log (usuario, fecha, tabla, operacion, datos)
        VALUES (
            current_user,
            now(),
            TG_TABLE_NAME,
            TG_OP,
            jsonb_build_object('antes', to_jsonb(OLD), 'despues', to_jsonb(NEW))
        );
        RETURN NEW;
    ELSIF (TG_OP = 'INSERT') THEN
        INSERT INTO auditoria_log (usuario, fecha, tabla, operacion, datos)
        VALUES (current_user, now(), TG_TABLE_NAME, TG_OP, to_jsonb(NEW));
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Triggers sobre tablas clínicas sensibles: paciente, expediente y consulta
DROP TRIGGER IF EXISTS trg_auditoria_paciente ON paciente;
CREATE TRIGGER trg_auditoria_paciente
    AFTER INSERT OR UPDATE OR DELETE ON paciente
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria_general();

DROP TRIGGER IF EXISTS trg_auditoria_expediente ON expediente;
CREATE TRIGGER trg_auditoria_expediente
    AFTER INSERT OR UPDATE OR DELETE ON expediente
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria_general();

DROP TRIGGER IF EXISTS trg_auditoria_consulta ON consulta;
CREATE TRIGGER trg_auditoria_consulta
    AFTER INSERT OR UPDATE OR DELETE ON consulta
    FOR EACH ROW EXECUTE FUNCTION fn_auditoria_general();

-- 3. PRUEBA DE FUNCIONAMIENTO DE AUDITORÍA
