--        --   'ddl'   : registra CREATE, ALTER y DROP sobre objetos de BD.
--        --   'role'  : registra GRANT, REVOKE, CREATE/ALTER/DROP ROLE.
--        --   'all'   : registra todas las categorías anteriores.
