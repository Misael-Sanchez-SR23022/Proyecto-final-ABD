-- ============================================================================

-- 1. ALERTA DE ESPACIO LIBRE EN DISCO (< 20 % sobre volumen asignado de 50 GB)
WITH disco AS (
    SELECT
        50.0 * 1024 * 1024 * 1024 AS capacidad_total_bytes,
        pg_database_size(current_database()) AS usado_bd_bytes
)
SELECT
    'Espacio libre en disco (< 20%)' AS regla_alerta,
    pg_size_pretty(usado_bd_bytes::bigint) AS espacio_usado,
    ROUND(((capacidad_total_bytes - usado_bd_bytes) / capacidad_total_bytes) * 100, 2) || ' %' AS porcentaje_libre,
    '20.00 %' AS umbral_minimo,
    CASE
        WHEN ((capacidad_total_bytes - usado_bd_bytes) / capacidad_total_bytes) * 100 < 20
        THEN 'CRÍTICO: Espacio libre inferior al 20%'
        ELSE 'OK: Espacio disponible dentro de rango seguro'
    END AS estado_alerta
FROM disco;

-- 2. ALERTA DE CRECIMIENTO SEMANAL DE LA BASE DE DATOS (> 2 GB)
CREATE TABLE IF NOT EXISTS control_crecimiento_bd (
    id_medicion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_medicion TIMESTAMP NOT NULL DEFAULT now(),
    tamano_bytes BIGINT NOT NULL
);

-- Registrar línea base de hace 7 días (si no existe) y medición actual
INSERT INTO control_crecimiento_bd (fecha_medicion, tamano_bytes)
SELECT now() - INTERVAL '7 days', GREATEST(pg_database_size(current_database()) - 5242880, 0)
WHERE NOT EXISTS (SELECT 1 FROM control_crecimiento_bd);

INSERT INTO control_crecimiento_bd (fecha_medicion, tamano_bytes)
VALUES (now(), pg_database_size(current_database()));

WITH mediciones AS (
    SELECT
        (SELECT tamano_bytes FROM control_crecimiento_bd ORDER BY fecha_medicion DESC LIMIT 1) AS actual_bytes,
        (SELECT tamano_bytes FROM control_crecimiento_bd WHERE fecha_medicion <= now() - INTERVAL '7 days' ORDER BY fecha_medicion DESC LIMIT 1) AS semana_pasada_bytes,
        2.0 * 1024 * 1024 * 1024 AS umbral_crecimiento_bytes
)
SELECT
    'Crecimiento semanal de BD (> 2 GB)' AS regla_alerta,
    pg_size_pretty(actual_bytes - COALESCE(semana_pasada_bytes, actual_bytes)) AS crecimiento_7_dias,
    '2.00 GB' AS umbral_maximo,
    CASE
        WHEN (actual_bytes - COALESCE(semana_pasada_bytes, actual_bytes)) > umbral_crecimiento_bytes
        THEN 'ALERTA: Crecimiento semanal supera los 2 GB'
        ELSE 'OK: Crecimiento semanal normal'
    END AS estado_alerta
FROM mediciones;

-- 3. ALERTA DE TAMAÑO MÁXIMO POR PARTICIÓN (> 5 GB)
WITH particiones AS (
    SELECT
        c.relname AS nombre_particion,
        pg_total_relation_size(c.oid) AS tamano_bytes
    FROM pg_partition_tree('consulta') pt
    JOIN pg_class c ON c.oid = pt.relid
    WHERE pt.isleaf
    UNION ALL
    SELECT
        c.relname AS nombre_particion,
        pg_total_relation_size(c.oid) AS tamano_bytes
    FROM pg_partition_tree('estudio_diagnostico') pt
    JOIN pg_class c ON c.oid = pt.relid
    WHERE pt.isleaf
),
mayor_particion AS (
    SELECT * FROM particiones ORDER BY tamano_bytes DESC LIMIT 1
)
SELECT
    'Partición más grande (> 5 GB)' AS regla_alerta,
    nombre_particion AS particion_mayor,
    pg_size_pretty(tamano_bytes) AS tamano_actual,
    '5.00 GB' AS umbral_maximo,
    CASE
        WHEN tamano_bytes > (5.0 * 1024 * 1024 * 1024)
        THEN 'ALERTA: Partición supera los 5 GB (evaluar rotación/archivado)'
        ELSE 'OK: Tamaño de partición dentro del límite'
    END AS estado_alerta
FROM mayor_particion;