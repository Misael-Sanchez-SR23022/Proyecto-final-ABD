-- =====================================================================
-- 6. QUIRÓFANOS, CIRUGÍAS Y EQUIPO QUIRÚRGICO
-- =====================================================================

CREATE TABLE tipo_quirofano (
    id_tipo_quirofano BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE quirofano (
    id_quirofano BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_quirofano BIGINT NOT NULL REFERENCES tipo_quirofano (id_tipo_quirofano),
    nombre_quirofano VARCHAR(80) NOT NULL UNIQUE,
    piso SMALLINT,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    CONSTRAINT ck_quirofano_estado CHECK (
        estado IN ('DISPONIBLE', 'OCUPADO', 'MANTENIMIENTO', 'FUERA_DE_SERVICIO')
    )
);

CREATE TABLE tipo_cirugia (
    id_tipo_cirugia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_especialidad BIGINT REFERENCES especialidad (id_especialidad),
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT,
    duracion_estimada_minutos INTEGER NOT NULL,
    complejidad VARCHAR(30) NOT NULL,
    CONSTRAINT ck_tipocirugia_duracion CHECK (duracion_estimada_minutos > 0),
    CONSTRAINT ck_tipocirugia_complejidad CHECK (
        complejidad IN ('BAJA', 'MEDIA', 'ALTA')
    )
);

CREATE TABLE cirugia (
    id_cirugia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ingreso_hospitalario BIGINT NOT NULL REFERENCES ingreso_hospitalario (id_ingreso_hospitalario),
    id_quirofano BIGINT NOT NULL REFERENCES quirofano (id_quirofano),
    id_cirujano_principal BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_anestesiologo BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_tipo_cirugia BIGINT NOT NULL REFERENCES tipo_cirugia (id_tipo_cirugia),
    fecha_hora_programada TIMESTAMP NOT NULL,
    fecha_hora_inicio TIMESTAMP,
    fecha_hora_fin TIMESTAMP,
    diagnostico_preoperatorio TEXT NOT NULL,
    diagnostico_posoperatorio TEXT,
    observaciones TEXT,
    estado_cirugia VARCHAR(25) NOT NULL DEFAULT 'PROGRAMADA',
    CONSTRAINT ck_cirugia_estado CHECK (
        estado_cirugia IN ('PROGRAMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA')
    ),
    CONSTRAINT ck_cirugia_distintos CHECK (
        id_cirujano_principal <> id_anestesiologo
    ),
    CONSTRAINT ck_cirugia_horas CHECK (
        fecha_hora_fin IS NULL
        OR (
            fecha_hora_inicio IS NOT NULL
            AND fecha_hora_fin > fecha_hora_inicio
        )
    ),

    CONSTRAINT ex_cirugia_quirofano EXCLUDE USING gist (
        id_quirofano
        WITH
            =,
            tsrange (
                fecha_hora_inicio,
                fecha_hora_fin
            )
        WITH
            &&
    )
    WHERE (
            fecha_hora_inicio IS NOT NULL
            AND fecha_hora_fin IS NOT NULL
            AND estado_cirugia <> 'CANCELADA'
        ),
        CONSTRAINT ex_cirugia_cirujano EXCLUDE USING gist (
            id_cirujano_principal
            WITH
                =,
                tsrange (
                    fecha_hora_inicio,
                    fecha_hora_fin
                )
            WITH
                &&
        )
    WHERE (
            fecha_hora_inicio IS NOT NULL
            AND fecha_hora_fin IS NOT NULL
            AND estado_cirugia <> 'CANCELADA'
        ),
        CONSTRAINT ex_cirugia_anestesiologo EXCLUDE USING gist (
            id_anestesiologo
            WITH
                =,
                tsrange (
                    fecha_hora_inicio,
                    fecha_hora_fin
                )
            WITH
                &&
        )
    WHERE (
            fecha_hora_inicio IS NOT NULL
            AND fecha_hora_fin IS NOT NULL
            AND estado_cirugia <> 'CANCELADA'
        )
);

CREATE TABLE cirugia_equipo (
    id_cirugia BIGINT NOT NULL REFERENCES cirugia (id_cirugia) ON DELETE CASCADE,
    id_empleado BIGINT NOT NULL REFERENCES empleado (id_empleado),
    rol VARCHAR(40) NOT NULL,
    PRIMARY KEY (id_cirugia, id_empleado),
    CONSTRAINT ck_cirugiaequipo_rol CHECK (
        rol IN ('CIRUJANO_ASISTENTE', 'ENFERMERA_INSTRUMENTISTA', 'ENFERMERA_CIRCULANTE', 'OTRO')
    )
);

