-- 4. CAMAS E INGRESOS
-- =====================================================================

CREATE TABLE tipo_cama (
    id_tipo_cama BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE cama (
    id_cama BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_cama BIGINT NOT NULL REFERENCES tipo_cama (id_tipo_cama),
    id_departamento BIGINT NOT NULL REFERENCES departamento (id_departamento),
    numero_cama VARCHAR(20) NOT NULL,
    habitacion VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    CONSTRAINT ck_cama_estado CHECK (
        estado IN ('DISPONIBLE', 'OCUPADA', 'LIMPIEZA', 'MANTENIMIENTO')
    ),
    CONSTRAINT uq_cama_ubicacion UNIQUE (
        id_departamento,
        habitacion,
        numero_cama
    )
);

CREATE TABLE ingreso_hospitalario (
    id_ingreso_hospitalario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente (id_paciente),
    id_medico_ingreso BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_cama BIGINT NOT NULL REFERENCES cama (id_cama),
    tipo_ingreso VARCHAR(20) NOT NULL,
    fecha_hora_ingreso TIMESTAMP NOT NULL DEFAULT now(),
    motivo_ingreso TEXT NOT NULL,
    diagnostico_ingreso TEXT,
    fecha_hora_alta TIMESTAMP,
    motivo_alta TEXT,
    diagnostico_alta TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_ingreso_tipo CHECK (
        tipo_ingreso IN ('URGENCIAS', 'PROGRAMADO', 'REFERENCIA')
    ),
    CONSTRAINT ck_ingreso_estado CHECK (
        estado IN ('ACTIVO', 'ALTA', 'CANCELADO')
    ),
    CONSTRAINT ck_ingreso_fechas CHECK (
        fecha_hora_alta IS NULL
        OR fecha_hora_alta >= fecha_hora_ingreso
    ),
    CONSTRAINT ck_ingreso_activo CHECK (
        estado <> 'ACTIVO'
        OR fecha_hora_alta IS NULL
    ),
    CONSTRAINT ck_ingreso_alta CHECK (
        estado <> 'ALTA'
        OR fecha_hora_alta IS NOT NULL
    )
);

