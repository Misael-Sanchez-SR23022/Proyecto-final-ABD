        correo ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    )
);

-- =====================================================================
-- 3. PACIENTES Y EXPEDIENTE
-- =====================================================================

CREATE TABLE paciente (
    id_paciente BIGINT PRIMARY KEY REFERENCES persona (id_persona), -- PK y FK (subtipo)
    tipo_sangre VARCHAR(5),
    estatura NUMERIC(4, 2),
    peso NUMERIC(5, 2),
    CONSTRAINT ck_paciente_sangre CHECK (
        tipo_sangre IS NULL
        OR tipo_sangre IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    CONSTRAINT ck_paciente_estatura CHECK (
        estatura IS NULL
        OR (
            estatura > 0.30
            AND estatura < 2.60
        )
    ),
    CONSTRAINT ck_paciente_peso CHECK (
        peso IS NULL
        OR peso > 0
    )
);

CREATE TABLE expediente (
    id_expediente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL UNIQUE REFERENCES paciente (id_paciente), -- un expediente por paciente
    numero_expediente VARCHAR(30) NOT NULL UNIQUE,
    fecha_apertura DATE NOT NULL DEFAULT CURRENT_DATE
);

