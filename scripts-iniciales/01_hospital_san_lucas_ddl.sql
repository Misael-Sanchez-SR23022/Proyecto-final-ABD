CREATE EXTENSION IF NOT EXISTS btree_gist;  -- necesaria para las restricciones de exclusión

-- =====================================================================
-- 1. PERSONAS Y CONTACTO
-- =====================================================================

CREATE TABLE persona (
    id_persona BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dui VARCHAR(10) UNIQUE, -- NULL permitido (menores, extranjeros)
    primer_nombre VARCHAR(60) NOT NULL,
    segundo_nombre VARCHAR(60),
    primer_apellido VARCHAR(60) NOT NULL,
    segundo_apellido VARCHAR(60),
    fecha_nacimiento DATE NOT NULL,
    genero VARCHAR(20) NOT NULL,
    CONSTRAINT ck_persona_dui CHECK (
        dui IS NULL
        OR dui ~ '^[0-9]{8}-[0-9]$'
    ),
    CONSTRAINT ck_persona_genero CHECK (
        genero IN ('MASCULINO', 'FEMENINO', 'OTRO')
    ),
    CONSTRAINT ck_persona_fnac CHECK (
        fecha_nacimiento <= DATE '2100-01-01'
        AND fecha_nacimiento >= DATE '1900-01-01'
    )
);

CREATE TABLE telefono_persona (
    id_telefono BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL REFERENCES persona (id_persona),
    telefono VARCHAR(20) NOT NULL,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_telefono_formato CHECK (
        telefono ~ '^[0-9+() -]{7,20}$'
    ),
    CONSTRAINT uq_telefono_persona UNIQUE (id_persona, telefono)
);

CREATE TABLE direccion (
    id_direccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calle VARCHAR(150) NOT NULL,
    colonia VARCHAR(100),
    municipio VARCHAR(100) NOT NULL,
    departamento_geo VARCHAR(100) NOT NULL,
    codigo_postal VARCHAR(15),
    pais VARCHAR(60) NOT NULL DEFAULT 'El Salvador'
);

CREATE TABLE direccion_persona (
    id_persona BIGINT NOT NULL REFERENCES persona (id_persona),
    id_direccion BIGINT NOT NULL REFERENCES direccion (id_direccion),
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id_persona, id_direccion)
);

CREATE TABLE contacto_emergencia (
    id_contacto_emergencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primer_nombre VARCHAR(60) NOT NULL,
    primer_apellido VARCHAR(60) NOT NULL,
    telefono_emergencia VARCHAR(20) NOT NULL,
    CONSTRAINT ck_contacto_tel CHECK (
        telefono_emergencia ~ '^[0-9+() -]{7,20}$'
    )
);

CREATE TABLE persona_contacto_emergencia (
    id_persona BIGINT NOT NULL REFERENCES persona (id_persona),
    id_contacto_emergencia BIGINT NOT NULL REFERENCES contacto_emergencia (id_contacto_emergencia),
    parentesco VARCHAR(40) NOT NULL,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (
        id_persona,
        id_contacto_emergencia
    )
);

-- =====================================================================
-- 2. CATÁLOGOS DE PERSONAL Y DEPARTAMENTOS
-- =====================================================================

CREATE TABLE especialidad (
    id_especialidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_especialidad VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_especialidad_estado CHECK (
        estado IN ('ACTIVO', 'INACTIVO')
    )
);

CREATE TABLE cargo (
    id_cargo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cargo VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_cargo_estado CHECK (
        estado IN ('ACTIVO', 'INACTIVO')
    )
);

CREATE TABLE departamento (
    id_departamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jefe_departamento BIGINT,
    nombre_departamento VARCHAR(100) NOT NULL UNIQUE,
    piso SMALLINT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_departamento_estado CHECK (
        estado IN ('ACTIVO', 'INACTIVO')
    )
);

CREATE TABLE empleado (
    id_empleado BIGINT PRIMARY KEY REFERENCES persona (id_persona), -- PK y FK (subtipo)
    id_cargo BIGINT NOT NULL REFERENCES cargo (id_cargo),
    id_especialidad BIGINT REFERENCES especialidad (id_especialidad), -- NULL para administrativos
    id_departamento BIGINT NOT NULL REFERENCES departamento (id_departamento),
    numero_licencia VARCHAR(30) UNIQUE, -- NULL si no aplica
    fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_empleado_estado CHECK (
        estado IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO')
    )       
);

