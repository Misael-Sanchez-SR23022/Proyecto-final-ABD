-- 11. ESTUDIOS DIAGNÓSTICOS (laboratorio e imagenología)
-- =====================================================================

CREATE TABLE tipo_estudio (
    id_tipo_estudio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    categoria VARCHAR(20) NOT NULL,
    descripcion TEXT,
    CONSTRAINT ck_tipoestudio_categoria CHECK (
        categoria IN ('LABORATORIO', 'IMAGENOLOGIA')
    )
);

CREATE TABLE estudio_diagnostico (
    id_estudio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente (id_paciente),
    id_medico_solicitante BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_tipo_estudio BIGINT NOT NULL REFERENCES tipo_estudio (id_tipo_estudio),
    id_equipo BIGINT REFERENCES equipo_medico (id_equipo), 
    id_tecnico BIGINT REFERENCES empleado (id_empleado), 
    fecha_hora_solicitud TIMESTAMP NOT NULL DEFAULT now(),
    fecha_hora_programada TIMESTAMP,
    fecha_hora_realizacion TIMESTAMP,
    fecha_hora_resultado TIMESTAMP,
    resultado TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'SOLICITADO',
    CONSTRAINT ck_estudio_estado CHECK (
        estado IN ('SOLICITADO', 'PROGRAMADO', 'REALIZADO', 'CON_RESULTADO', 'CANCELADO')
    ),
    CONSTRAINT ck_estudio_prog CHECK (
        fecha_hora_programada IS NULL
        OR fecha_hora_programada >= fecha_hora_solicitud
    ),
    CONSTRAINT ck_estudio_real CHECK (
        fecha_hora_realizacion IS NULL
        OR fecha_hora_realizacion >= fecha_hora_solicitud
    ),
    CONSTRAINT ck_estudio_result CHECK (
        fecha_hora_resultado IS NULL
        OR fecha_hora_resultado >= fecha_hora_solicitud
    )
);

CREATE TABLE detalle_resultado_estudio (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudio BIGINT NOT NULL REFERENCES estudio_diagnostico (id_estudio) ON DELETE CASCADE,
    parametro VARCHAR(100) NOT NULL,
    valor VARCHAR(100) NOT NULL,
    unidad VARCHAR(30),
    rango_referencia VARCHAR(100),
    CONSTRAINT uq_detalle_resultado UNIQUE (id_estudio, parametro)
);