CREATE TABLE tipo_turno (
    id_tipo_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE turno (
    id_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_tipo_turno BIGINT NOT NULL REFERENCES tipo_turno (id_tipo_turno),
    id_departamento BIGINT NOT NULL REFERENCES departamento (id_departamento),
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO',
    CONSTRAINT ck_turno_estado CHECK (
        estado IN ('PROGRAMADO', 'EN_CURSO', 'COMPLETADO', 'AUSENTE', 'CANCELADO')
    ),
    CONSTRAINT ck_turno_horas CHECK (
        fecha_hora_fin > fecha_hora_inicio
    ),
    CONSTRAINT ex_turno_empleado EXCLUDE USING gist (
        id_empleado
        WITH
            =,
            tsrange (
                fecha_hora_inicio,
                fecha_hora_fin
            )
        WITH
            &&
    )
    WHERE (estado <> 'CANCELADO')
);

