-- 7. INVENTARIO
-- =====================================================================

CREATE TABLE tipo_insumo (
    id_tipo_insumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tipo VARCHAR(80) NOT NULL UNIQUE, 
    descripcion TEXT
);

CREATE TABLE insumo (
    id_insumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_insumo BIGINT NOT NULL REFERENCES tipo_insumo (id_tipo_insumo),
    nombre_insumo VARCHAR(120) NOT NULL UNIQUE,
    unidad_medida VARCHAR(30) NOT NULL DEFAULT 'UNIDAD',
    stock INTEGER NOT NULL DEFAULT 0, 
    stock_minimo INTEGER NOT NULL DEFAULT 0,
    precio NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_insumo_stock CHECK (stock >= 0),
    CONSTRAINT ck_insumo_minimo CHECK (stock_minimo >= 0),
    CONSTRAINT ck_insumo_precio CHECK (precio >= 0)
);

CREATE TABLE movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_cirugia BIGINT REFERENCES cirugia (id_cirugia), 
    id_departamento BIGINT REFERENCES departamento (id_departamento),
    tipo_movimiento VARCHAR(20) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_movimiento_tipo CHECK (
        tipo_movimiento IN ('ENTRADA', 'SALIDA', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO')
    ),
    CONSTRAINT ck_movimiento_destino CHECK (
        tipo_movimiento = 'SALIDA'
        OR id_cirugia IS NULL
    )
);

CREATE TABLE detalle_movimiento_inventario (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_movimiento BIGINT NOT NULL REFERENCES movimiento_inventario (id_movimiento),
    id_insumo BIGINT NOT NULL REFERENCES insumo (id_insumo),
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0),
    CONSTRAINT uq_detalle_insumo UNIQUE (id_movimiento, id_insumo)
);

