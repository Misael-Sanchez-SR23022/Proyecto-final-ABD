    responsable VARCHAR(120), 
    costo NUMERIC(12, 2),
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO',
    CONSTRAINT ck_mant_estado CHECK (
        estado IN ('PROGRAMADO', 'EN_PROCESO', 'REALIZADO', 'CANCELADO')
