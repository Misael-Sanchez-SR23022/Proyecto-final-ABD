-- 9. INTERCONSULTAS
-- =====================================================================

CREATE TABLE interconsulta (
    id_interconsulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente (id_paciente),
    id_medico_solicitante BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_medico_especialista BIGINT NOT NULL REFERENCES empleado (id_empleado),
    id_especialidad_solicitada BIGINT NOT NULL REFERENCES especialidad (id_especialidad),
    prioridad VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    motivo_solicitud TEXT NOT NULL,
    diagnostico_respuesta TEXT,
    fecha_hora_solicitud TIMESTAMP NOT NULL DEFAULT now(),
    fecha_hora_respuesta TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'SOLICITADA',
    CONSTRAINT ck_interconsulta_estado CHECK (
        estado IN ('SOLICITADA', 'EN_PROCESO', 'RESPONDIDA', 'CANCELADA')
    ),
    CONSTRAINT ck_interconsulta_prioridad CHECK (
        prioridad IN ('BAJA', 'NORMAL', 'URGENTE')
    ),
    CONSTRAINT ck_interconsulta_medicos CHECK (
        id_medico_solicitante <> id_medico_especialista
    ),
    CONSTRAINT ck_interconsulta_fechas CHECK (
        fecha_hora_respuesta IS NULL
        OR fecha_hora_respuesta >= fecha_hora_solicitud
    )
);

