        estado IN ('OPERATIVO', 'EN_MANTENIMIENTO', 'FUERA_DE_SERVICIO', 'BAJA')
    )
);

CREATE TABLE tipo_mantenimiento (
    id_tipo_mantenimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE, 
    descripcion TEXT
);

CREATE TABLE mantenimiento_equipo (
    id_mantenimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo BIGINT NOT NULL REFERENCES equipo_medico (id_equipo),
    id_tipo_mantenimiento BIGINT NOT NULL REFERENCES tipo_mantenimiento (id_tipo_mantenimiento),
