--  ============================================================================
-- 3. TRIGGER: completar fecha_hora_solicitud en detalle_resultado_estudio
--  ============================================================================
CREATE OR REPLACE FUNCTION fn_detalle_estudio_set_fecha()
RETURNS trigger AS $$
BEGIN
    IF NEW.fecha_hora_solicitud IS NULL THEN
        SELECT e.fecha_hora_solicitud
          INTO NEW.fecha_hora_solicitud
          FROM estudio_diagnostico e
         WHERE e.id_estudio = NEW.id_estudio
         LIMIT 1;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_detalle_estudio_set_fecha ON detalle_resultado_estudio;

CREATE TRIGGER trg_detalle_estudio_set_fecha
BEFORE INSERT ON detalle_resultado_estudio
FOR EACH ROW EXECUTE FUNCTION fn_detalle_estudio_set_fecha();

COMMIT;

