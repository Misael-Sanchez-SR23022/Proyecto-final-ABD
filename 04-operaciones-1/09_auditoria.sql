CREATE TABLE IF NOT EXISTS auditoria_log (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(60) NOT NULL DEFAULT session_user,
    fecha TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    tabla VARCHAR(60) NOT NULL,
    operacion VARCHAR(10) NOT NULL,
    datos JSONB
);

ALTER TABLE auditoria_log
    ADD COLUMN IF NOT EXISTS rol_activo VARCHAR(60),
    ADD COLUMN IF NOT EXISTS aplicacion TEXT,
    ADD COLUMN IF NOT EXISTS ip_cliente INET;

ALTER TABLE auditoria_log
    ALTER COLUMN usuario SET DEFAULT session_user;

CREATE OR REPLACE FUNCTION fn_auditoria_general()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_datos JSONB;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_datos := to_jsonb(NEW);
    ELSIF TG_OP = 'UPDATE' THEN
        v_datos := jsonb_build_object(
            'antes', to_jsonb(OLD),
            'despues', to_jsonb(NEW)
        );
    ELSIF TG_OP = 'DELETE' THEN
        v_datos := to_jsonb(OLD);
    ELSE
        RAISE EXCEPTION 'Operación de auditoría no soportada: %', TG_OP;
    END IF;

    INSERT INTO public.auditoria_log
        (usuario, rol_activo, fecha, tabla, operacion, datos, aplicacion, ip_cliente)
    VALUES
        (
            session_user,
            current_user,
            clock_timestamp(),
            TG_TABLE_NAME,
            TG_OP,
            v_datos,
            NULLIF(current_setting('application_name', true), ''),
            inet_client_addr()
        );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

-- Evitar que usuarios comunes consulten o manipulen directamente la bitácora.
REVOKE ALL ON TABLE auditoria_log FROM PUBLIC;
REVOKE ALL ON FUNCTION fn_auditoria_general() FROM PUBLIC;

-- Reinstalar triggers sin duplicarlos.
DROP TRIGGER IF EXISTS trg_auditoria_paciente ON paciente;
CREATE TRIGGER trg_auditoria_paciente
AFTER INSERT OR UPDATE OR DELETE ON paciente
FOR EACH ROW EXECUTE FUNCTION fn_auditoria_general();

